// hashPassword hashes a password using Argon2id with a random salt.
// Format: $argon2id$salt_b64$hash_b64
func (s *Service) hashPassword(password string) (string, error) {
	salt := make([]byte, 16)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}

	hash := argon2.IDKey(
		[]byte(password),
		salt,
		s.cfg.Argon2Iterations,
		s.cfg.Argon2Memory,
		s.cfg.Argon2Parallelism,
		32,
	)

	encoded := fmt.Sprintf("$argon2id$%s$%s",
		base64.RawStdEncoding.EncodeToString(salt),
		base64.RawStdEncoding.EncodeToString(hash),
	)
	return encoded, nil
}

// verifyPassword checks a plain password against a stored Argon2id hash.
func (s *Service) verifyPassword(password, encoded string) bool {
	parts := strings.Split(encoded, "$")
	if len(parts) != 4 || parts[1] != "argon2id" {
		return false
	}

	salt, err := base64.RawStdEncoding.DecodeString(parts[2])
	if err != nil {
		return false
	}
	storedHash, err := base64.RawStdEncoding.DecodeString(parts[3])
	if err != nil {
		return false
	}

	computed := argon2.IDKey(
		[]byte(password),
		salt,
		s.cfg.Argon2Iterations,
		s.cfg.Argon2Memory,
		s.cfg.Argon2Parallelism,
		32,
	)

	// Constant-time comparison
	if len(computed) != len(storedHash) {
		return false
	}
	var diff byte
	for i := range computed {
		diff |= computed[i] ^ storedHash[i]
	}
	return diff == 0
}

