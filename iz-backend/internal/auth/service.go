// Token Refresh
// ────────────────────────────────────────────────────────────────

// RefreshOutput holds the new token pair returned after a successful refresh.
type RefreshOutput struct {
	AccessToken  string
	RefreshToken string
}

// RefreshTokens validates the opaque refresh token, rotates it (single-use),
// and returns a fresh access + refresh token pair.
func (s *Service) RefreshTokens(ctx context.Context, rawRefreshToken string) (*RefreshOutput, error) {
	tokenHash := hashToken(rawRefreshToken)

	// Look up the hashed token — must not be revoked and not yet expired,
	// and the owning user must be active.
	var userID string
	var isAdmin bool
	err := s.db.QueryRow(ctx, `
		SELECT rt.user_id, u.is_admin
		FROM refresh_tokens rt
		JOIN users u ON u.id = rt.user_id
		WHERE rt.token_hash = $1
		  AND rt.revoked    = FALSE
		  AND rt.expires_at > NOW()
		  AND u.is_deleted  = FALSE
		  AND u.is_banned   = FALSE`,
		tokenHash,
	).Scan(&userID, &isAdmin)

	if errors.Is(err, pgx.ErrNoRows) {
		s.log.Warn().Msg("refresh token not found or expired")
		return nil, ErrTokenInvalid
	}
	if err != nil {
		return nil, fmt.Errorf("query refresh token: %w", err)
	}

	// Revoke the old refresh token immediately (token rotation — single-use).
	_, err = s.db.Exec(ctx,
		`UPDATE refresh_tokens SET revoked = TRUE WHERE token_hash = $1`,
		tokenHash)
	if err != nil {
		return nil, fmt.Errorf("revoke refresh token: %w", err)
	}

	// Issue a brand-new access + refresh token pair.
	access, refresh, err := s.issueTokens(ctx, userID, "", isAdmin)
	if err != nil {
		return nil, err
	}

	// Update last_seen_at
	_, _ = s.db.Exec(ctx, `UPDATE users SET last_seen_at = NOW() WHERE id = $1`, userID)

	s.log.Info().Str("user_id", userID).Msg("refresh token rotated")
	return &RefreshOutput{AccessToken: access, RefreshToken: refresh}, nil
}

