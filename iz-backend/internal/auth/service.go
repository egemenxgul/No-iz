// Common errors
var (
	ErrInvalidCredentials = errors.New("invalid credentials")
	ErrUserNotFound       = errors.New("user not found")
	ErrUsernameTaken      = errors.New("username already taken")
	ErrEmailTaken         = errors.New("email already taken")
	ErrInvalidInviteCode  = errors.New("invalid or expired invite code")
	ErrInviteCodeFull     = errors.New("invite code has reached its usage limit")
	ErrTokenExpired       = errors.New("token expired")
	ErrTokenInvalid       = errors.New("invalid token")
	ErrUserBanned         = errors.New("account is banned")
)

// Service handles all authentication logic.
type Service struct {
	db  *pgxpool.Pool
	rdb *redis.Client
	cfg *config.Config
	log zerolog.Logger
}

// NewService creates a new auth service.
func NewService(db *pgxpool.Pool, rdb *redis.Client, cfg *config.Config, log zerolog.Logger) *Service {
	return &Service{db: db, rdb: rdb, cfg: cfg, log: log.With().Str("svc", "auth").Logger()}
}

