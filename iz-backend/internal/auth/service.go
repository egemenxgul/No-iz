type UserBundle struct {
	UserID          string `json:"user_id"`
	IdentityKey     string `json:"identity_key"`
	SignedPrekey    string `json:"signed_prekey"`
	SignedPrekeySig string `json:"signed_prekey_sig"`
	OneTimePrekey   *OneTimePrekey `json:"one_time_prekey,omitempty"`
}

// GetUserBundle fetches the Signal protocol pre-key bundle for a user.
// It also fetches and marks one one-time prekey as used.
func (s *Service) GetUserBundle(ctx context.Context, userID string) (*UserBundle, error) {
	var bundle UserBundle
	err := s.db.QueryRow(ctx, `
		SELECT id, identity_key, signed_prekey, signed_prekey_sig
		FROM users WHERE id = $1`, userID).Scan(
		&bundle.UserID, &bundle.IdentityKey, &bundle.SignedPrekey, &bundle.SignedPrekeySig,
	)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, ErrUserNotFound
		}
		return nil, fmt.Errorf("fetch user keys: %w", err)
	}

	// Fetch one unused one-time prekey (optional but recommended in Signal)
	var otpk OneTimePrekey
	err = s.db.QueryRow(ctx, `
		UPDATE user_prekeys
		SET used = TRUE
		WHERE id = (
			SELECT id FROM user_prekeys
			WHERE user_id = $1 AND used = FALSE
			ORDER BY created_at ASC
			LIMIT 1
			FOR UPDATE SKIP LOCKED
		)
		RETURNING key_id, public_key`, userID).Scan(&otpk.KeyID, &otpk.PublicKey)
	
	if err == nil {
		bundle.OneTimePrekey = &otpk
	} else if !errors.Is(err, pgx.ErrNoRows) {
		s.log.Warn().Err(err).Str("user_id", userID).Msg("failed to fetch one-time prekey")
	}

	return &bundle, nil
}

