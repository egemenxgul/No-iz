type RegisterDeviceInput struct {
	DeviceName  string `json:"device_name"`
	DeviceToken string `json:"device_token"`
	Platform    string `json:"platform"` // ios | android | web
	IdentityKey string `json:"identity_key,omitempty"`
}

// RegisterDevice registers a device token for push notifications and Signal protocol bundle mapping.
func (s *Service) RegisterDevice(ctx context.Context, userID string, input *RegisterDeviceInput) error {
	if input.DeviceToken == "" {
		return fmt.Errorf("device token is required")
	}
	if input.Platform != "ios" && input.Platform != "android" && input.Platform != "web" {
		return fmt.Errorf("invalid platform: %s", input.Platform)
	}
	if input.DeviceName == "" {
		input.DeviceName = "Unknown Device"
	}

	uid, err := uuid.Parse(userID)
	if err != nil {
		return fmt.Errorf("invalid user id: %w", err)
	}

	// If identity key is empty, fetch user's primary identity key
	if input.IdentityKey == "" {
		var primaryKey string
		err := s.db.QueryRow(ctx, `SELECT identity_key FROM users WHERE id = $1`, uid).Scan(&primaryKey)
		if err != nil {
			return fmt.Errorf("get user identity key: %w", err)
		}
		input.IdentityKey = primaryKey
	}

	// Upsert user device: If device token already exists for this user, update. Otherwise insert.
	var deviceID string
	err = s.db.QueryRow(ctx, `
		SELECT id FROM user_devices 
		WHERE user_id = $1 AND (device_token = $2 OR identity_key = $3)`,
		uid, input.DeviceToken, input.IdentityKey,
	).Scan(&deviceID)

	if err == nil {
		// Update existing device
		_, err = s.db.Exec(ctx, `
			UPDATE user_devices 
			SET device_name = $1, device_token = $2, platform = $3, last_active_at = NOW()
			WHERE id = $4`,
			input.DeviceName, input.DeviceToken, input.Platform, deviceID,
		)
		if err != nil {
			return fmt.Errorf("update user device: %w", err)
		}
	} else {
		// Insert new device
		_, err = s.db.Exec(ctx, `
			INSERT INTO user_devices (user_id, device_name, device_token, platform, identity_key)
			VALUES ($1, $2, $3, $4, $5)`,
			uid, input.DeviceName, input.DeviceToken, input.Platform, input.IdentityKey,
		)
		if err != nil {
			return fmt.Errorf("insert user device: %w", err)
		}
	}

	s.log.Info().Str("user_id", userID).Str("platform", input.Platform).Msg("device token registered")
	return nil
}

