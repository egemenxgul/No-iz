func normalizePhone(phone string) string {
	var sb strings.Builder
	for _, r := range phone {
		if (r >= '0' && r <= '9') || r == '+' {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

// ContactMatchResult represents a matched contact user.
type ContactMatchResult struct {
	ID          string `json:"id"`
	Username    string `json:"username"`
	DisplayName string `json:"display_name"`
	AvatarURL   string `json:"avatar_url"`
	Phone       string `json:"phone"`
}

// MatchContacts matches a list of phone numbers against registered users.
func (s *Service) MatchContacts(ctx context.Context, phoneNumbers []string) ([]ContactMatchResult, error) {
	if len(phoneNumbers) == 0 {
		return []ContactMatchResult{}, nil
	}

	// Normalize input phone numbers
	normalized := make([]string, 0, len(phoneNumbers))
	for _, p := range phoneNumbers {
		norm := normalizePhone(p)
		if norm != "" {
			normalized = append(normalized, norm)
		}
	}

	if len(normalized) == 0 {
		return []ContactMatchResult{}, nil
	}

	// Query registered users with matching phone numbers
	rows, err := s.db.Query(ctx, `
		SELECT id, username, display_name, avatar_url, phone FROM users
		WHERE phone = ANY($1) AND is_deleted = FALSE AND is_banned = FALSE`,
		normalized,
	)
	if err != nil {
		return nil, fmt.Errorf("match contacts: %w", err)
	}
	defer rows.Close()

	var results []ContactMatchResult
	for rows.Next() {
		var r ContactMatchResult
		var phoneVal *string
		if err := rows.Scan(&r.ID, &r.Username, &r.DisplayName, &r.AvatarURL, &phoneVal); err != nil {
			continue
		}
		if phoneVal != nil {
			r.Phone = *phoneVal
		}
		results = append(results, r)
	}

	if results == nil {
		results = []ContactMatchResult{}
	}
	return results, nil
}
