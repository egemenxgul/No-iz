// LoginInput holds login credentials.
type LoginInput struct {
	EmailOrUsername string
	Password        string
}

// LoginOutput is returned on successful login.
type LoginOutput struct {
	UserID       string
	Username     string
	DisplayName  string
	AvatarURL    string
	IsAdmin      bool
	AccessToken  string `json:"access_token,omitempty"`
	RefreshToken string `json:"refresh_token,omitempty"`
	Requires2FA  bool   `json:"requires_2fa"`
	TempToken    string `json:"temp_token,omitempty"`
}

// Login authenticates a user and returns tokens.
func (s *Service) Login(ctx context.Context, in LoginInput) (*LoginOutput, error) {
	var userID, hash, username, displayName, avatarURL string
	var isAdmin bool

	var isTotpEnabled bool

	emailHash := s.hashEmail(in.EmailOrUsername)
	err := s.db.QueryRow(ctx, `
		SELECT id, password_hash, username, display_name, avatar_url, is_admin, is_totp_enabled FROM users
		WHERE (username = $1 OR email_hash = $2)
		  AND is_deleted = FALSE AND is_banned = FALSE
		LIMIT 1`,
		in.EmailOrUsername,
		emailHash,
	).Scan(&userID, &hash, &username, &displayName, &avatarURL, &isAdmin, &isTotpEnabled)

	if errors.Is(err, pgx.ErrNoRows) {
		s.log.Warn().Str("input", in.EmailOrUsername).Msg("user not found in db")
		// CWE-208 / Timing Attack Prevention: perform a dummy hash comparison so that
		// the response time is identical whether or not the user exists.
		s.verifyPassword(in.Password, "$argon2id$v=19,m=65536,t=3,p=4$dGltaW5nYXR0YWNr$dGltaW5nYXR0YWNrdGltaW5nYXR0YWNr")
		return nil, ErrInvalidCredentials
	}
	if err != nil {
		return nil, fmt.Errorf("query user: %w", err)
	}

	if !s.verifyPassword(in.Password, hash) {
		s.log.Warn().Str("user_id", userID).Msg("password verification failed")
		return nil, ErrInvalidCredentials
	}

	// Update last_seen_at
	_, _ = s.db.Exec(ctx, `UPDATE users SET last_seen_at = NOW() WHERE id = $1`, userID)

	if isTotpEnabled {
		tempToken, err := s.issueTempToken(userID)
		if err != nil {
			return nil, fmt.Errorf("issue temp token: %w", err)
		}
		return &LoginOutput{
			UserID:      userID,
			Username:    username,
			DisplayName: displayName,
			AvatarURL:   avatarURL,
			IsAdmin:     isAdmin,
			Requires2FA: true,
			TempToken:   tempToken,
		}, nil
	}

	access, refresh, err := s.issueTokens(ctx, userID, "", isAdmin)
	if err != nil {
		return nil, err
	}

	return &LoginOutput{
		UserID:       userID,
		Username:     username,
		DisplayName:  displayName,
		AvatarURL:    avatarURL,
		IsAdmin:      isAdmin,
		AccessToken:  access,
		RefreshToken: refresh,
		Requires2FA:  false,
	}, nil
}

