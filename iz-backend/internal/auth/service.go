type UserSearchResult struct {
	ID          string `json:"id"`
	Username    string `json:"username"`
	DisplayName string `json:"display_name"`
	AvatarURL   string `json:"avatar_url"`
}

// SearchUsers searches for users by username prefix (case-insensitive).
func (s *Service) SearchUsers(ctx context.Context, query string, limit int) ([]UserSearchResult, error) {
	rows, err := s.db.Query(ctx, `
		SELECT id, username, display_name, avatar_url
		FROM users
		WHERE username ILIKE $1
		  AND is_deleted = FALSE AND is_banned = FALSE
		ORDER BY username ASC
		LIMIT $2`,
		query+"%", limit,
	)
	if err != nil {
		return nil, fmt.Errorf("search users: %w", err)
	}
	defer rows.Close()

	var results []UserSearchResult
	for rows.Next() {
		var u UserSearchResult
		if err := rows.Scan(&u.ID, &u.Username, &u.DisplayName, &u.AvatarURL); err != nil {
			continue
		}
		results = append(results, u)
	}
	if results == nil {
		results = []UserSearchResult{}
	}
	return results, nil
}

// ValidateAccessToken parses and validates a JWT access token.
func (s *Service) ValidateAccessToken(tokenStr string) (*izClaims, error) {
	token, err := jwt.ParseWithClaims(tokenStr, &izClaims{}, func(t *jwt.Token) (interface{}, error) {
		if _, ok := t.Method.(*jwt.SigningMethodHMAC); !ok {
			return nil, fmt.Errorf("unexpected signing method: %v", t.Header["alg"])
		}
		return []byte(s.cfg.JWTAccessSecret), nil
	})
	if err != nil {
		if errors.Is(err, jwt.ErrTokenExpired) {
			return nil, ErrTokenExpired
		}
		return nil, ErrTokenInvalid
	}

	claims, ok := token.Claims.(*izClaims)
	if !ok || !token.Valid {
		return nil, ErrTokenInvalid
	}
	return claims, nil
}

