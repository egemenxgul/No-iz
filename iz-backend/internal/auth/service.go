func (s *Service) ExportData(ctx context.Context, userID string) (map[string]any, error) {
	data := make(map[string]any)
	
	// User profile
	var username, emailHash, displayName, phone *string
	var createdAt time.Time
	err := s.db.QueryRow(ctx, "SELECT username, email_hash, display_name, phone, created_at FROM users WHERE id = $1", userID).Scan(&username, &emailHash, &displayName, &phone, &createdAt)
	if err == nil {
		data["profile"] = map[string]any{
			"username":     username,
			"display_name": displayName,
			"phone":        phone,
			"created_at":   createdAt,
		}
	}

	// Friendships
	rows, err := s.db.Query(ctx, "SELECT user_id1, user_id2, status FROM friendships WHERE user_id1 = $1 OR user_id2 = $1", userID)
	if err == nil {
		var friends []map[string]any
		for rows.Next() {
			var u1, u2, status string
			if err := rows.Scan(&u1, &u2, &status); err == nil {
				friends = append(friends, map[string]any{"user_id1": u1, "user_id2": u2, "status": status})
			}
		}
		rows.Close()
		data["friendships"] = friends
	}

	return data, nil
}

func (s *Service) DeleteAccount(ctx context.Context, userID string, password string) error {
	var hash string
	err := s.db.QueryRow(ctx, "SELECT password_hash FROM users WHERE id = $1", userID).Scan(&hash)
	if err != nil {
		return fmt.Errorf("query user: %w", err)
	}

	if !s.verifyPassword(password, hash) {
		return ErrInvalidCredentials
	}

	// Anonymize user to comply with GDPR but keep db constraints intact
	anonUsername := "deleted_user_" + userID[:8]
	_, err = s.db.Exec(ctx, `
		UPDATE users 
		SET username = $1, email = $2, email_hash = $2, phone = NULL, display_name = 'Deleted User', avatar_url = '', bio = '', is_deleted = TRUE, password_hash = '', totp_secret = NULL, is_totp_enabled = FALSE
		WHERE id = $3
	`, anonUsername, uuid.NewString()+"@deleted.local", userID)
	
	if err != nil {
		return fmt.Errorf("delete account: %w", err)
	}

	// Also revoke all refresh tokens
	_, _ = s.db.Exec(ctx, "UPDATE refresh_tokens SET revoked = TRUE WHERE user_id = $1", userID)

	return nil
}

