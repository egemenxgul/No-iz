const inviteCodeChars = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789" // no O,0,I,1 (ambiguous)

// GenerateInviteCode creates a random uppercase invite code of given length.
func GenerateInviteCode(length int) (string, error) {
	code := make([]byte, length)
	for i := range code {
		n, err := rand.Int(rand.Reader, big.NewInt(int64(len(inviteCodeChars))))
		if err != nil {
			return "", err
		}
		code[i] = inviteCodeChars[n.Int64()]
	}
	return string(code), nil
}

func generateRandomToken(n int) (string, error) {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.URLEncoding.EncodeToString(b), nil
}

// hashToken creates a real SHA-256 hash of the refresh token for safe DB storage.
func hashToken(token string) string {
	sum := sha256.Sum256([]byte(token))
	return base64.URLEncoding.EncodeToString(sum[:])
}

func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}

