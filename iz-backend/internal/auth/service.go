// Invite code helpers
// ────────────────────────────────────────────────────────────────

func (s *Service) validateInviteCode(ctx context.Context, code string) (string, error) {
	code = strings.ToUpper(strings.TrimSpace(code))
	if code == "" {
		return "", ErrInvalidInviteCode
	}

	var codeID string
	var maxUses, useCount int
	var isActive bool

	err := s.db.QueryRow(ctx, `
		SELECT id, max_uses, use_count, is_active FROM invite_codes
		WHERE code = $1
		  AND (expires_at IS NULL OR expires_at > NOW())`,
		code,
	).Scan(&codeID, &maxUses, &useCount, &isActive)

	if errors.Is(err, pgx.ErrNoRows) || !isActive {
		return "", ErrInvalidInviteCode
	}
	if err != nil {
		return "", fmt.Errorf("query invite code: %w", err)
	}

	if useCount >= maxUses {
		return "", ErrInviteCodeFull
	}

	return codeID, nil
}

func (s *Service) getInvitedByID(ctx context.Context, codeID string) (*uuid.UUID, error) {
	var creatorID *uuid.UUID
	_ = s.db.QueryRow(ctx, `SELECT created_by_id FROM invite_codes WHERE id = $1`, codeID).Scan(&creatorID)
	return creatorID, nil
}

func (s *Service) useInviteCode(ctx context.Context, codeID string, userID uuid.UUID) error {
	_, err := s.db.Exec(ctx, `
		UPDATE invite_codes SET use_count = use_count + 1 WHERE id = $1`, codeID)
	if err != nil {
		return err
	}
	_, err = s.db.Exec(ctx, `
		INSERT INTO invite_uses (code_id, used_by_id) VALUES ($1, $2)`, codeID, userID)
	return err
}

// ────────────────────────────────────────────────────────────────
// Prekey helpers
// ────────────────────────────────────────────────────────────────

func (s *Service) storePrekeys(ctx context.Context, userID uuid.UUID, keys []OneTimePrekey) error {
	for _, k := range keys {
		_, err := s.db.Exec(ctx, `
			INSERT INTO user_prekeys (user_id, key_id, public_key)
			VALUES ($1, $2, $3) ON CONFLICT (user_id, key_id) DO NOTHING`,
			userID, k.KeyID, k.PublicKey,
		)
		if err != nil {
			return err
		}
	}
	return nil
}

// GetPrekeysCount returns the number of remaining one-time prekeys for the given user.
func (s *Service) GetPrekeysCount(ctx context.Context, userID uuid.UUID) (int, error) {
	var count int
	err := s.db.QueryRow(ctx,
		`SELECT COUNT(*) FROM user_prekeys WHERE user_id = $1 AND used = false`,
		userID,
	).Scan(&count)
	if err != nil {
		return 0, fmt.Errorf("get prekeys count: %w", err)
	}
	return count, nil
}

// ReplenishPrekeys stores additional one-time prekeys supplied by the client.
func (s *Service) ReplenishPrekeys(ctx context.Context, userID uuid.UUID, keys []OneTimePrekey) error {
	if len(keys) == 0 {
		return fmt.Errorf("no prekeys provided")
	}
	if len(keys) > 200 {
		return fmt.Errorf("too many prekeys: max 200 per request")
	}
	return s.storePrekeys(ctx, userID, keys)
}

// ────────────────────────────────────────────────────────────────
// Password helpers
