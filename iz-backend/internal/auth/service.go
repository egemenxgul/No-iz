type Generate2FAOutput struct {
	Secret string `json:"secret"`
	URL    string `json:"url"`
}

func (s *Service) Generate2FA(ctx context.Context, userID string) (*Generate2FAOutput, error) {
	var username string
	err := s.db.QueryRow(ctx, "SELECT username FROM users WHERE id = $1", userID).Scan(&username)
	if err != nil {
		return nil, fmt.Errorf("query user: %w", err)
	}

	key, err := totp.Generate(totp.GenerateOpts{
		Issuer:      "No-iz",
		AccountName: username,
	})
	if err != nil {
		return nil, fmt.Errorf("generate totp: %w", err)
	}

	secret := key.Secret()
	_, err = s.db.Exec(ctx, "UPDATE users SET totp_secret = $1 WHERE id = $2", secret, userID)
	if err != nil {
		return nil, fmt.Errorf("update totp secret: %w", err)
	}

	return &Generate2FAOutput{
		Secret: secret,
		URL:    key.URL(),
	}, nil
}

func (s *Service) Verify2FA(ctx context.Context, userID string, code string) error {
	var secret string
	err := s.db.QueryRow(ctx, "SELECT totp_secret FROM users WHERE id = $1", userID).Scan(&secret)
	if err != nil {
		return fmt.Errorf("query secret: %w", err)
	}
	if secret == "" {
		return errors.New("totp secret not found")
	}

	valid := totp.Validate(code, secret)
	if !valid {
		return errors.New("invalid totp code")
	}

	_, err = s.db.Exec(ctx, "UPDATE users SET is_totp_enabled = TRUE WHERE id = $1", userID)
	if err != nil {
		return fmt.Errorf("update totp enabled: %w", err)
	}

	return nil
}

type Finalize2FALoginInput struct {
	TempToken string
	Code      string
}

func (s *Service) Finalize2FALogin(ctx context.Context, in Finalize2FALoginInput) (*LoginOutput, error) {
	userID, err := s.validateTempToken(in.TempToken)
	if err != nil {
		return nil, fmt.Errorf("invalid temp token: %w", err)
	}

	var secret, username, displayName, avatarURL string
	var isAdmin, isTotpEnabled bool
	err = s.db.QueryRow(ctx, `
		SELECT totp_secret, username, display_name, avatar_url, is_admin, is_totp_enabled
		FROM users WHERE id = $1 AND is_deleted = FALSE AND is_banned = FALSE
	`, userID).Scan(&secret, &username, &displayName, &avatarURL, &isAdmin, &isTotpEnabled)
	if err != nil {
		return nil, fmt.Errorf("query user: %w", err)
	}

	if !isTotpEnabled {
		return nil, errors.New("2fa is not enabled for this user")
	}

	valid := totp.Validate(in.Code, secret)
	if !valid {
		return nil, errors.New("invalid totp code")
	}

	access, refresh, err := s.issueTokens(ctx, userID, "", isAdmin)
	if err != nil {
		return nil, err
	}

	return &LoginOutput{
		UserID:       userID,
		Username:     username,
		DisplayName:  displayName,
		AvatarURL:    avatarURL,
		IsAdmin:      isAdmin,
		AccessToken:  access,
		RefreshToken: refresh,
		Requires2FA:  false,
	}, nil
}

func (s *Service) issueTempToken(userID string) (string, error) {
	now := time.Now()
	claims := jwt.RegisteredClaims{
		ExpiresAt: jwt.NewNumericDate(now.Add(10 * time.Minute)),
		IssuedAt:  jwt.NewNumericDate(now),
		Subject:   userID,
	}
	return jwt.NewWithClaims(jwt.SigningMethodHS256, claims).SignedString([]byte(s.cfg.JWTAccessSecret))
}

func (s *Service) validateTempToken(tokenStr string) (string, error) {
	token, err := jwt.ParseWithClaims(tokenStr, &jwt.RegisteredClaims{}, func(t *jwt.Token) (interface{}, error) {
		if _, ok := t.Method.(*jwt.SigningMethodHMAC); !ok {
			return nil, fmt.Errorf("unexpected signing method")
		}
		return []byte(s.cfg.JWTAccessSecret), nil
	})
	if err != nil {
		return "", ErrTokenInvalid
	}
	claims, ok := token.Claims.(*jwt.RegisteredClaims)
	if !ok || !token.Valid {
		return "", ErrTokenInvalid
	}
	return claims.Subject, nil
}

type izClaims struct {
	UserID  string `json:"uid"`
	IsAdmin bool   `json:"adm"`
	jwt.RegisteredClaims
}

// issueTokens creates and stores a new access + refresh token pair.
func (s *Service) issueTokens(ctx context.Context, userID, deviceID string, isAdmin bool) (access, refresh string, err error) {
	now := time.Now()

	// Access token (short-lived, stateless JWT)
	accessClaims := izClaims{
		UserID:  userID,
		IsAdmin: isAdmin,
		RegisteredClaims: jwt.RegisteredClaims{
			ExpiresAt: jwt.NewNumericDate(now.Add(s.cfg.JWTAccessTTL)),
			IssuedAt:  jwt.NewNumericDate(now),
			Subject:   userID,
		},
	}
	access, err = jwt.NewWithClaims(jwt.SigningMethodHS256, accessClaims).
		SignedString([]byte(s.cfg.JWTAccessSecret))
	if err != nil {
		return "", "", fmt.Errorf("sign access token: %w", err)
	}

	// Refresh token (opaque random token stored in DB)
	rawRefresh, err := generateRandomToken(32)
	if err != nil {
		return "", "", fmt.Errorf("generate refresh token: %w", err)
	}
	refreshHash := hashToken(rawRefresh)
	expiresAt := now.Add(s.cfg.JWTRefreshTTL)

	_, err = s.db.Exec(ctx, `
		INSERT INTO refresh_tokens (user_id, token_hash, expires_at)
		VALUES ($1, $2, $3)`,
		userID, refreshHash, expiresAt,
	)
	if err != nil {
		return "", "", fmt.Errorf("store refresh token: %w", err)
	}

	return access, rawRefresh, nil
}

